marks = int(input("Enter the marks"))
if marks >=90:
    print("Student got A+")
elif marks >=80:
    print("Student got A")
elif marks >=70:
    print("Student got B+")
elif marks >=60:
    print("Student got B")
elif marks >=50:
    print("Student got C+")
elif marks>=40:
    print("Student got C")
else:
    print("fail")